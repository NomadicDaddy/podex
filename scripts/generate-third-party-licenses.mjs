import { readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

import { browserAssets, externalModules, vendoredAssets } from './lib/license-catalog.mjs';
import {
	collectClosure,
	findLicenseText,
	packageInfo,
	readManifest,
} from './lib/license-graph.mjs';

const root = process.cwd();
const summaryPath = join(root, 'THIRD_PARTY_LICENSES.md');
const noticesPath = join(root, 'THIRD_PARTY_NOTICES.md');
const checkOnly = process.argv.includes('--check');

function table(headers, rows) {
	const divider = headers.map(() => '---');
	return [headers, divider, ...rows].map((row) => `| ${row.join(' | ')} |`).join('\n');
}

function npmTable(names, installed) {
	return table(
		['Package', 'Installed version', 'License'],
		names.map((name) => {
			const info = installed.get(name);
			return [`\`${name}\``, info.version, info.license];
		})
	);
}

function renderSummary({ directDevelopment, directRuntime, graph, installed }) {
	const flagged = graph.filter((entry) => /GPL|MPL|CDDL|EUPL|SSPL/i.test(entry.license));
	const browserRows = browserAssets.map((asset) => {
		const info = installed.get(asset.name);
		return [`\`${asset.name}\``, info.version, info.license, asset.role];
	});
	const externalRows = externalModules.map((module) => [
		module.name,
		module.version,
		module.license,
		module.role,
		`[source](${module.source})`,
	]);
	const vendoredRows = vendoredAssets.map((asset) => [
		asset.name,
		asset.license,
		asset.paths,
		`[source](${asset.source})`,
	]);
	const flaggedRows = flagged.map((entry) => [`\`${entry.name}\``, entry.version, entry.license]);

	return `# Third-Party Licenses

> Generated by \`bun run licenses:generate\`. Do not edit manually.

Podex is licensed under the MIT License. This document records the third-party software used
to build and run Podex and distinguishes software copied into the release from tools and
external prerequisites that are not bundled.

## Distribution boundary

The defined Podex release is built from \`release-manifest.json\`. It includes the browser
assets and generated CSS below, but excludes \`node_modules\` and all installed PowerShell
modules. The latter remain separate installations carrying their own license files.

## Browser assets included in the release

${table(['Package', 'Version', 'License', 'How it ships'], browserRows)}

The complete license text and copyright notices for these packages are reproduced in
\`THIRD_PARTY_NOTICES.md\`, which must ship beside this file. The Mustache JavaScript and
generated Tailwind stylesheet also carry embedded copies of their applicable notices so the
notices remain attached when a browser receives either asset directly.

## Adapted htmx extension sources

${table(['Component', 'License', 'Local source', 'Upstream'], vendoredRows)}

These files were adapted for htmx 4 from htmx's 0BSD-licensed extension implementations.
Zero-Clause BSD permits copying and modification without an attribution condition; the
provenance is retained here for clarity.

## External PowerShell modules

${table(['Module', 'Expected range', 'License', 'Use', 'Upstream'], externalRows)}

Pode and PSSQLite are runtime prerequisites loaded from the user's PowerShell module path.
PSSQLite installation is currently a documented manual prerequisite. Pester and
PSScriptAnalyzer are development-only. Podex does not copy these modules into its release. If
a future artifact bundles them, it must also carry each module's own license and, for Pode,
its bundled third-party \`licenses/\` directory.

## Direct npm dependencies

These packages are installed to build the browser assets; npm packages themselves are not
included in the release.

### Application and asset-build dependencies

${npmTable(directRuntime, installed)}

### Development dependencies

${npmTable(directDevelopment, installed)}

## Copyleft and weak-copyleft build components

The installed npm closure contains the following copyleft or weak-copyleft packages:

${flaggedRows.length > 0 ? table(['Package', 'Version', 'License'], flaggedRows) : 'None.'}

These packages are build tools or their native dependencies and are excluded from the Podex
release. In particular, Tailwind uses Lightning CSS under MPL-2.0 to transform CSS. The
generated CSS does not contain Lightning CSS code, so MPL-2.0 does not apply to Podex or the
generated stylesheet. Sharp and its libvips binaries are development-only. A future artifact
that bundles \`node_modules\`, Lightning CSS, Sharp, or libvips must be assessed separately and
must carry the licenses and source notices required by those packages.

## Regeneration and verification

Run \`bun install --frozen-lockfile\`, then \`bun run licenses:generate\` after changing a
dependency or redistributed asset. \`bun run check:licenses\` fails when either generated
document differs from the installed, locked dependency graph. \`bun run release:check\` then
verifies that both notice documents travel with the staged release.
`;
}

async function renderNotices(installed) {
	const sections = [];
	for (const asset of browserAssets) {
		const info = installed.get(asset.name);
		const licenseText = (await findLicenseText(root, info.directory)).trim();
		sections.push(
			`## ${info.name}@${info.version}\n\nLicense: ${info.license}\n\n${licenseText}`
		);
	}

	return `# Third-Party Notices

> Generated by \`bun run licenses:generate\`. Do not edit manually.

This appendix contains the notices and license texts for third-party browser assets copied or
compiled into the Podex release. The release does not include \`node_modules\` or installed
PowerShell modules.

${sections.join('\n\n---\n\n')}
`;
}

async function writeOrCheck(path, content) {
	if (!checkOnly) {
		await writeFile(path, content, 'utf8');
		return true;
	}

	const current = await readFile(path, 'utf8').catch(() => '');
	if (current === content) return true;
	console.error(`${relative(root, path)} is out of date.`);
	return false;
}

async function main() {
	const rootManifest = await readManifest(join(root, 'package.json'));
	const directRuntime = Object.keys(rootManifest.dependencies ?? {}).sort();
	const directDevelopment = Object.keys(rootManifest.devDependencies ?? {}).sort();
	const graph = await collectClosure(root, [...directRuntime, ...directDevelopment]);
	const unknown = graph.filter((entry) => entry.license === 'UNKNOWN');
	if (unknown.length > 0) {
		throw new Error(
			`Installed packages lack license metadata: ${unknown.map((entry) => `${entry.name}@${entry.version}`).join(', ')}`
		);
	}
	const restrictive = graph.filter((entry) => entry.license === 'RESTRICTIVE');
	if (restrictive.length > 0) {
		throw new Error(
			`Installed packages carry restrictive, source-available, non-commercial, or proprietary license terms that require manual review: ${restrictive
				.map((entry) => `${entry.name}@${entry.version}`)
				.join(', ')}. Resolve or exclude the package before generating license documents.`
		);
	}
	const installed = new Map();

	for (const name of new Set([...directRuntime, ...directDevelopment])) {
		installed.set(name, await packageInfo(root, name));
	}

	const summary = renderSummary({ directDevelopment, directRuntime, graph, installed });
	const notices = await renderNotices(installed);
	const results = await Promise.all([
		writeOrCheck(summaryPath, summary),
		writeOrCheck(noticesPath, notices),
	]);

	if (results.every(Boolean)) {
		console.log(
			checkOnly
				? 'Third-party license documents match the installed dependency graph.'
				: 'Generated THIRD_PARTY_LICENSES.md and THIRD_PARTY_NOTICES.md.'
		);
		return;
	}

	console.error('Run `bun run licenses:generate` and commit the generated documents.');
	process.exitCode = 1;
}

main().catch((error) => {
	console.error(error instanceof Error ? error.message : String(error));
	process.exitCode = 1;
});
